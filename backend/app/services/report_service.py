"""
Report Generation Service.
Generates comprehensive Markdown and JSON reports for security audits and academic evaluations.
"""
import json
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, Optional

from backend.app.core.config import settings
from backend.app.database.session import SessionLocal
from backend.app.database.models import ScanRunRecord

class ReportService:
    def __init__(self):
        self.reports_dir = settings.REPORTS_DIR
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def generate_demo_summary(self) -> Dict[str, Any]:
        """Generates a comprehensive system demonstration report summary."""
        # Read model metrics
        metrics_file = settings.METRICS_DIR / "comparison_results.json"
        metrics_data = {}
        if metrics_file.exists():
            with open(metrics_file, "r", encoding="utf-8") as f:
                metrics_data = json.load(f)

        # Query recent scans
        db = SessionLocal()
        try:
            recent_scans = db.query(ScanRunRecord).order_by(ScanRunRecord.created_at.desc()).limit(10).all()
            scan_summaries = [
                {
                    "run_id": s.run_id,
                    "artifact_name": s.artifact_name,
                    "policy_decision": s.policy_decision,
                    "risk_score": s.risk_score,
                    "created_at": s.created_at.isoformat() if s.created_at else ""
                }
                for s in recent_scans
            ]
        finally:
            db.close()

        summary = {
            "project_title": "Ransomware Behavior Detection via Graph Neural Networks in CI/CD Supply Chain",
            "report_generated_at": datetime.utcnow().isoformat(),
            "active_model": settings.DEFAULT_MODEL,
            "models_evaluated": list(metrics_data.keys()),
            "model_metrics": metrics_data,
            "recent_pipeline_runs": scan_summaries,
            "policy_thresholds": {
                "PASS": f"Risk Score < {settings.RISK_THRESHOLD_PASS}",
                "WARN": f"Risk Score {settings.RISK_THRESHOLD_PASS} - {settings.RISK_THRESHOLD_WARN}",
                "BLOCK": f"Risk Score >= {settings.RISK_THRESHOLD_BLOCK}"
            }
        }

        # Save to disk
        out_file = self.reports_dir / "latest_demonstration_report.json"
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)

        return summary

    def generate_markdown_report(self, run_id: str) -> str:
        """Generates a formatted markdown report for an individual CI/CD scan run."""
        db = SessionLocal()
        try:
            record = db.query(ScanRunRecord).filter(ScanRunRecord.run_id == run_id).first()
            if not record:
                return f"# Security Report\n\nRun ID {run_id} not found."

            details = json.loads(record.details_json) if record.details_json else {}
        finally:
            db.close()

        md = f"""# Artifact Security Screening Report

**Run ID:** `{record.run_id}`  
**Artifact Name:** `{record.artifact_name}`  
**Pipeline Stage:** {record.pipeline_stage}  
**Scan Timestamp:** {record.created_at}  

---

## Executive Gate Decision: **{record.policy_decision}**

- **Security Risk Score:** {record.risk_score} / 100
- **Behavioral Classification:** {details.get('predicted_class', 'Unknown')}
- **Model Confidence:** {details.get('confidence', 0.0) * 100:.2f}%
- **Inference Model Backbone:** {details.get('model_used', 'GAT').upper()}
- **Total API Events Analyzed:** {details.get('total_calls', 0)}

---

## Detected Policy Violations
"""
        violations = details.get("violations", [])
        if not violations:
            md += "\n*No policy violations detected. Build artifact complies with security thresholds.*\n"
        else:
            for v in violations:
                md += f"\n- **[{v.get('severity')}] {v.get('rule_id')}:** {v.get('description')}"

        md += "\n\n---\n*Report generated by GNN Behavior Screening Gate (Defensive Supply Chain Security).*\n"
        return md

report_service = ReportService()
